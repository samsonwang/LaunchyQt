const ushort zhCN_min = 0x4E00;
// Last MAPPED code point, not one past it: zhCNInitial() compares inclusively.
const ushort zhCN_max = static_cast<ushort>(zhCN_min + sizeof(zhCN_table) - 2);

// The table is only correct while it covers exactly the GB2312 Han block it
// claims. A truncated or extended literal has to fail the build, not quietly
// shift every initial after the edit.
static_assert(sizeof(zhCN_table) - 1 == static_cast<size_t>(0x9FA5) - 0x4E00 + 1,
              "zhCN_table must hold one initial for every code point of U+4E00..U+9FA5");

